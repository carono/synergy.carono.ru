<h3>Исходный кейс</h3>
<div class="alert-info alert">Дан одномерный массив А размерности N. Найти сумму отрицательных элементов, расположенных между максимальным и минимальным. Ответом на задачу будет ссылка на репозиторий GitHub, где хранится Ваша программа. Или иным удобным для Вас способом.</div>

<h2>Функциональность</h2>
<p>Код выполняет основную задачу, но содержит критические отклонения от требований:</p>
<ul>
    <li>Ожидает строку вместо массива, нарушая условие ввода</li>
    <li>Возвращает массив с отладочными данными вместо числа (суммы)</li>
    <li>Не обрабатывает случаи с отсутствием отрицательных элементов (возвращает 0, что корректно)</li>
    <li>Нарушена типизация: при пустом вводе возвращается массив, хотя по логике должна быть сумма</li>
</ul>

<h2>Производительность</h2>
<p>Алгоритм эффективен (O(n)), но избыточные операции снижают скорость:</p>
<ul>
    <li>Преобразование строки в массив не требуется по условию</li>
    <li>Двойной обход массива (поиск индексов и суммирование) можно объединить</li>
</ul>

<h2>Удобство использования</h2>
<ul>
    <li>Нестандартный формат ввода (строка вместо массива) усложняет применение</li>
    <li>Избыточные возвращаемые данные затрудняют интерпретацию результата</li>
</ul>

<h2>Безопасность</h2>
<ul>
    <li>Использование is_numeric допускает строки с числами ("123"), но не защищает от некорректных типов</li>
    <li>Нет валидации на минимальный размер массива (должен быть ≥2 элемента)</li>
</ul>

<h2>Масштабируемость</h2>
<ul>
    <li>Жесткая привязка к строковому вводу ограничивает адаптацию под другие форматы данных</li>
    <li>Отсутствие параметров для настройки логики (например, включение границ в диапазон)</li>
</ul>

<h2>Переносимость</h2>
<ul>
    <li>Зависимость от preg_split делает код неприменимым для других типов данных</li>
    <li>Жесткая типизация возвращаемого значения (массив) усложняет интеграцию</li>
</ul>

<h2>Качество кода</h2>
<ul>
    <li>Нарушение принципа единственной ответственности: функция выполняет парсинг, поиск и фильтрацию</li>
    <li>Смешение уровней абстракции (логика парсинга и математических операций)</li>
</ul>

<h2>Тестирование</h2>
<p>Критически не хватает обработки случаев:</p>
<ul>
    <li>Все элементы положительные/отрицательные</li>
    <li>Min и max в начале/конце массива</li>
    <li>Нечисловые данные в строковом вводе</li>
</ul>